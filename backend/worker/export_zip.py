"""Confluence '공간 내보내기(HTML)' zip 을 ConfluenceClient 와 같은 인터페이스로 읽는 어댑터.

API 호출이 막힌 환경에서 브라우저로 내려받은 zip 을 적재할 때 쓴다. run_sync.py 가 --source export 일 때
ConfluenceClient 대신 이 클래스를 만들어 넘기므로, 파싱·청킹·임베딩·적재·변경 감지·삭제 정리는 그대로 동작한다.

HTML 내보내기 구조 (Cloud · Data Center 공통, 최상위 폴더가 있을 수도 없을 수도 있다):
  index.html                       공간 홈 + 페이지 트리
  <제목>_<페이지id>.html            페이지 1개 (id 가 없는 변형도 있어 그때는 파일명 해시를 id 로 쓴다)
  attachments/<페이지id>/<파일>     첨부 (파일명은 첨부 id 또는 원본 이름)
  images/, styles/                 아이콘·CSS (무시)

내보내기에 없는 것과 대체 규칙:
  버전        → 0 고정. 변경 감지는 본문 해시로만 한다
  수정일      → 페이지 footer 의 'Document generated by Confluence on …' 시각, 없으면 zip 항목 시각
  조회 제한   → 없음. EXPORT_ALLOWED_GROUPS 의 공간별 그룹을 쓴다 (기본 '*')
  첨부 원본명 → 페이지 하단 'Attachments' 절의 링크 텍스트. 없으면 zip 안 파일명
"""
import hashlib
import io
import logging
import os
import re
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import AsyncIterator, Dict, List, Optional

from bs4 import BeautifulSoup

from app.config import settings
from worker.confluence_client import ConfluenceAttachment, ConfluencePage

logger = logging.getLogger(__name__)

_PAGE_ID_RE = re.compile(r"_(\d+)\.html?$")
_GENERATED_RE = re.compile(r"generated by Confluence on\s+([^\n<]+)", re.I)
_DATE_FORMATS = ("%b %d, %Y %H:%M", "%b %d, %Y, %H:%M", "%Y-%m-%d %H:%M", "%d %b %Y %H:%M")


def parse_allowed_groups(spec: str, space_key: str) -> List[str]:
    """EXPORT_ALLOWED_GROUPS 해석. 'PROJ=pm,finance;NET=infra;*=*' 또는 그냥 'pm,finance' (모든 공간 공통)."""
    spec = (spec or "*").strip()
    if "=" not in spec:
        return [g.strip() for g in spec.split(",") if g.strip()] or ["*"]
    table: Dict[str, List[str]] = {}
    for part in spec.split(";"):
        if "=" not in part:
            continue
        k, v = part.split("=", 1)
        table[k.strip()] = [g.strip() for g in v.split(",") if g.strip()] or ["*"]
    return table.get(space_key) or table.get("*") or ["*"]


def _parse_generated(text: str) -> Optional[datetime]:
    m = _GENERATED_RE.search(text or "")
    if not m:
        return None
    raw = m.group(1).strip().rstrip(".")
    for fmt in _DATE_FORMATS:
        try:
            return datetime.strptime(raw, fmt).replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    return None


class ExportZipClient:
    """zip(또는 풀어 둔 디렉터리) 을 읽어 ConfluenceClient 와 같은 메서드를 제공한다."""

    def __init__(self, path: str, space_key: str, *, base_url: Optional[str] = None):
        self.path = Path(path)
        self.space_key = space_key
        self.base_url = (base_url if base_url is not None else settings.confluence_base_url).rstrip("/")
        self._zip: Optional[zipfile.ZipFile] = None
        self._names: List[str] = []
        self._prefix = ""  # 최상위 폴더 (있으면 'SPACE/')
        self._pages: Dict[str, ConfluencePage] = {}
        self._attachments: Dict[str, List[ConfluenceAttachment]] = {}
        self._att_paths: Dict[str, str] = {}  # attachment id → zip 내 경로
        self.generated_at: Optional[datetime] = None
        self._load()

    # ── 파일 접근 ────────────────────────────────────────────────────────────
    def _open(self):
        if self.path.is_dir():
            names = [str(p.relative_to(self.path)).replace(os.sep, "/") for p in self.path.rglob("*") if p.is_file()]
            return None, names
        z = zipfile.ZipFile(self.path)
        return z, [n for n in z.namelist() if not n.endswith("/")]

    def _read(self, name: str) -> bytes:
        if self._zip is not None:
            return self._zip.read(name)
        return (self.path / name).read_bytes()

    def _mtime(self, name: str) -> datetime:
        if self._zip is not None:
            return datetime(*self._zip.getinfo(name).date_time, tzinfo=timezone.utc)
        return datetime.fromtimestamp((self.path / name).stat().st_mtime, tz=timezone.utc)

    # ── 적재 ───────────────────────────────────────────────────────────────
    def _load(self) -> None:
        self._zip, self._names = self._open()
        index = next((n for n in self._names if n.endswith("index.html") and n.count("/") <= 1), None)
        if index is None:
            raise RuntimeError(f"index.html 을 찾을 수 없습니다. Confluence HTML 내보내기 zip 이 맞는지 확인하세요: {self.path}")
        self._prefix = index[: -len("index.html")]
        index_html = self._read(index).decode("utf-8", errors="replace")
        # footer 의 'Document generated by Confluence on …' 는 태그 사이에 있으므로 텍스트로 풀어서 찾는다
        self.generated_at = _parse_generated(BeautifulSoup(index_html, "html.parser").get_text("\n"))

        page_files = [n for n in self._names if n.startswith(self._prefix) and n.lower().endswith((".html", ".htm"))
                      and n[len(self._prefix):].count("/") == 0 and n != index]
        for name in page_files:
            try:
                self._load_page(name)
            except Exception as e:  # noqa: BLE001
                logger.warning("export page skipped %s: %s", name, e)
        # 페이지 HTML 에서 참조되지 않은 첨부도 폴더 기준으로 붙인다
        for name in self._names:
            rel = name[len(self._prefix):]
            m = re.match(r"attachments/(\d+)/([^/]+)$", rel)
            if not m:
                continue
            pid, fname = m.group(1), m.group(2)
            if pid in self._pages and not any(a.download_path == name for a in self._attachments.get(pid, [])):
                self._add_attachment(pid, name, fname)
        logger.info("export loaded: %s pages=%d attachments=%d generated=%s", self.path.name, len(self._pages),
                    sum(len(v) for v in self._attachments.values()), self.generated_at)

    def _load_page(self, name: str) -> None:
        rel = name[len(self._prefix):]
        m = _PAGE_ID_RE.search(rel)
        page_id = m.group(1) if m else "x" + hashlib.sha1(rel.encode()).hexdigest()[:12]
        html = self._read(name).decode("utf-8", errors="replace")
        soup = BeautifulSoup(html, "html.parser")

        title_el = soup.select_one("#title-text") or soup.find("title")
        title = (title_el.get_text(" ", strip=True) if title_el else rel.rsplit(".", 1)[0])
        title = re.sub(r"^[^:]+\s:\s", "", title)  # "SPACE : 제목" → "제목"

        ancestors: List[str] = []
        for li in soup.select("#breadcrumbs li"):
            t = li.get_text(" ", strip=True)
            if t:
                ancestors.append(t)
        if ancestors and ancestors[-1] == title:
            ancestors = ancestors[:-1]
        if ancestors:
            ancestors = ancestors[1:]  # 첫 항목은 공간 이름

        main = soup.select_one("#main-content") or soup.body or soup
        for junk in main.select(".pageSection, #footer, .footer-body, script, style"):
            junk.decompose()
        body_html = main.decode_contents()

        updated = _parse_generated(soup.get_text("\n")) or self._mtime(name)
        page = ConfluencePage(
            id=page_id, space_key=self.space_key, title=title, version=0, updated_at=updated, storage_html=body_html,
            ancestors=ancestors, url=self._page_url(page_id), read_groups=[], raw={"file": rel},
        )
        self._pages[page_id] = page

        # 'Attachments' 절의 링크에서 원본 파일명을 얻는다
        for a in soup.select("a[href^='attachments/']"):
            href = a.get("href", "")
            if not re.match(rf"attachments/{re.escape(page_id)}/[^/]+$", href):
                continue
            self._add_attachment(page_id, self._prefix + href, a.get_text(" ", strip=True) or href.rsplit("/", 1)[-1])

    def _add_attachment(self, page_id: str, zip_name: str, file_name: str) -> None:
        if zip_name not in self._names:
            return
        att_id = "a" + hashlib.sha1(zip_name.encode()).hexdigest()[:12]
        if att_id in self._att_paths:
            return
        self._att_paths[att_id] = zip_name
        size = self._zip.getinfo(zip_name).file_size if self._zip else (self.path / zip_name).stat().st_size
        self._attachments.setdefault(page_id, []).append(ConfluenceAttachment(
            id=att_id, page_id=page_id, file_name=file_name, media_type="", size=size, version=0,
            updated_at=self._pages[page_id].updated_at, download_path=zip_name, url=self._page_url(page_id),
        ))

    def _page_url(self, page_id: str) -> str:
        if self.base_url and page_id.isdigit():
            return f"{self.base_url}/pages/{page_id}"
        return f"export://{self.space_key}/{page_id}"

    # ── ConfluenceClient 와 같은 인터페이스 ─────────────────────────────────
    async def close(self) -> None:
        if self._zip is not None:
            self._zip.close()

    async def __aenter__(self):
        return self

    async def __aexit__(self, *exc):
        await self.close()

    async def iter_pages(self, space_key: str, *, modified_since: Optional[datetime] = None, page_size: int = 50) -> AsyncIterator[ConfluencePage]:
        """내보내기는 항상 전체 목록이다. modified_since 는 무시한다 (변경 감지는 해시로)."""
        for page in self._pages.values():
            yield page

    async def list_page_ids(self, space_key: str, *, page_size: int = 200) -> List[str]:
        return list(self._pages.keys())

    async def get_page(self, page_id: str) -> ConfluencePage:
        return self._pages[page_id]

    async def list_attachments(self, page_id: str, *, page_size: int = 100) -> List[ConfluenceAttachment]:
        return list(self._attachments.get(page_id, []))

    async def download_attachment(self, att: ConfluenceAttachment) -> bytes:
        return self._read(att.download_path)

    async def space_read_groups(self, space_key: str) -> List[str]:
        return parse_allowed_groups(settings.export_allowed_groups, space_key)
